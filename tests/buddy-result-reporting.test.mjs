import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { isolateHome } from './helpers/isolated-home.mjs';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'buddy-result-report-'));
isolateHome(home);
const { configManager } = await import('../dist/lib/config.js');
const { toolManager } = await import('../dist/lib/tool-manager.js');
const { marketModelService } = await import('../dist/lib/market-model-service.js');
const { applyTool } = await import('../dist/lib/core/tool-service.js');
const { commitWritePlan, previewWritePlan } = await import('../dist/lib/wizard/ui/write-plan.js');
const { renderResultSummary } = await import('../dist/lib/wizard/ui/tool-view.js');
const { uiRenderer } = await import('../dist/lib/wizard/ui/ui-renderer.js');
const { i18n } = await import('../dist/lib/i18n.js');
i18n.init('en_US');
test.after(() => fs.rmSync(home, { recursive: true, force: true }));
const available = { id: 'vendor/available', name: 'Available', features: ['工具调用'] };
for (const name of ['codebuddy', 'workbuddy']) {
 const field = name === 'codebuddy' ? 'codeBuddyModels' : 'workbuddyModels';
 test(`${name}: corrupt scalar model settings do not hide failure or other tool results`, async t => {
  t.mock.method(marketModelService, 'fetchModels', async () => [available]);
  configManager.setModels({ [field]: 'vendor/available' });
  const result = await applyTool(toolManager.get(name), { apiKey: 'fixture', baseUrl: 'https://example.com', models: configManager.getModels() });
  assert.equal(result.status, 'failed');
  const tables = [];
  t.mock.method(uiRenderer, 'renderTable', (headers, rows) => tables.push(rows));
  t.mock.method(console, 'log', () => {});
  renderResultSummary([result, { tool: {name:'other', displayName:'Other',command:'other',isInstalled:()=>true,defaultModel:'vendor/other'}, status:'success' }]);
  assert.equal(tables[0].length, 2);
  assert.match(tables[0][0][1], /failed/i);
  assert.match(tables[0][1][2], /vendor\/other/);
 });
 test(`${name}: plan results report only written models and warn about skipped IDs even with quiet writes`, async t => {
  t.mock.method(marketModelService, 'fetchModels', async () => [available]);
  const tool = toolManager.get(name);
  const selected = [available.id, 'vendor/delisted'];
  const models = { [field]: selected };
  configManager.setModels(models);
  const plan = {tool, models, main:available.id, changes:[], connection:{apiKey:'fixture',baseUrl:'https://example.com',endpoint:'custom'}};
  const file = path.join(home, '.' + name, 'models.json');
  const preview = await previewWritePlan([plan]);
  assert.equal(fs.existsSync(file), false);
  assert.deepEqual(preview.value[0].appliedModels, [available.id]);
  const results = await commitWritePlan([plan]);
  assert.equal(results[0].status, 'success');
  assert.deepEqual(results[0].appliedModels, [available.id]);
  assert.deepEqual(results[0].skippedModels, ['vendor/delisted']);
  const written = JSON.parse(fs.readFileSync(file, 'utf8'));
  assert.deepEqual((Array.isArray(written) ? written : written.models).map(model => model.id), [available.id]);
  assert.deepEqual(configManager.getModels()[field], selected);
  const tables = [], warnings = [];
  t.mock.method(uiRenderer, 'renderTable', (headers, rows) => tables.push(rows));
  t.mock.method(uiRenderer, 'renderWarning', text => warnings.push(text));
  t.mock.method(console, 'log', () => {});
  renderResultSummary(results);
  assert.match(tables[0][0][2], /vendor\/available/);
  assert.doesNotMatch(tables[0][0][2], /delisted/);
  assert.ok(warnings.some(text => text.includes('not written') && text.includes('vendor/delisted')));
  await tool.unloadConfig();
 });
}
